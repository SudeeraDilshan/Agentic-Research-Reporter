if __name__ == "__main__":
    query = "What are the latest architectures and breakthroughs in multi-agent LLM systems in 2025 and 2026?"

    print("=" * 68)
    print("  🤖 Agentic Research Reporter — Powered by Central MCP Server")
    print(f"  Query: {query}")
    print("=" * 68)

    thread = {"configurable": {"thread_id": "research-session-mcp-server"}}

    # Phase 1: Research until human approval gate
    print("\n--- PHASE 1: Supervisor Planning & Parallel MCP Tool Execution ---")
    result = app.invoke(
        {
            "query": query,
            "research_tasks": [],
            "research_findings": [],
            "sources": [],
            "human_approved": False,
            "draft_report": "",
            "edited_report": "",
            "final_report": "",
        },
        config=thread,
    )

    # Handle interrupt
    if "__interrupt__" in (result or {}):
        interrupt_data = result["__interrupt__"][0].value
        print("\n" + "=" * 68)
        print("  ⏸️  HUMAN APPROVAL REQUIRED")
        print("=" * 68)
        print(f"  {interrupt_data['message']}")
        print(f"\n  Research Preview:\n{interrupt_data['findings_preview']}")
        print(f"\n  Total Web Sources Discovered: {interrupt_data.get('total_sources_gathered', 0)}")

        # Human decision in terminal
        if "--auto-approve" in sys.argv:
            human_input = "yes"
            print(f"\n  [--auto-approve flag detected] Auto-approving report generation: '{human_input}'")
        elif sys.stdin.isatty():
            human_input = input(f"\n  {interrupt_data['question']}").strip()
        else:
            try:
                line = sys.stdin.readline().strip()
                human_input = line if line else "yes"
            except Exception:
                human_input = "yes"
            print(f"\n  [Non-interactive stdin]: '{human_input}'")

        # Phase 2: Resume report generation
        print("\n--- PHASE 2: Resuming Report Generation Pipeline ---")
        final_result = app.invoke(Command(resume=human_input), config=thread)
    else:
        final_result = result

    # Display Output
    print("\n" + "=" * 68)
    if final_result.get("final_report"):
        print("  ✅ FINAL GROUNDED RESEARCH REPORT")
        print("=" * 68)
        print(final_result["final_report"])
    else:
        print("  ❌ Report generation was cancelled by human.")
    print("=" * 68)
