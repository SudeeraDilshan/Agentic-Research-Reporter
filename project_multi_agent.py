# ── 1. Supervisor: Plans structured tasks & assigns MCP tools ───
def supervisor_node(state: MainState) -> dict:
    notify_node_event("supervisor", "started", {"query": state["query"]})
    print(f"\n🎯 [Supervisor] Planning research tasks via MCP Server tools…")
    available_tools = [t.name for t in get_mcp_tools()]
    print(f"   Available MCP Server Tools: {available_tools}")

    system = SystemMessage(content=(
        "You are an expert research supervisor coordinating a multi-agent investigation. "
        "Given the query, break it down into exactly 3 distinct, non-overlapping dimensions:\n"
        "1. Academic & Scientific Foundations (use tool: 'search_academic_papers')\n"
        "2. Industry Implementations & Current State (use tool: 'tavily_search')\n"
        "3. Future Directions, Challenges & Ethics (use tool: 'tavily_search')\n\n"
        "For each dimension, construct an optimized search query tailored to that MCP tool."
    ))

    tasks: List[Dict[str, Any]] = []
    try:
        structured_llm = llm.with_structured_output(SupervisorPlan)
        plan: SupervisorPlan = structured_llm.invoke([system, HumanMessage(content=state["query"])])
        tasks = [t.model_dump() for t in plan.tasks]
    except Exception as e:
        print(f"   ⚠️ Structured output fallback: {e}")
        query = state["query"]
        tasks = [
            {"id": 1, "focus": "Academic & Scientific Foundations", "tool_name": "search_academic_papers", "search_query": f"{query} architecture foundations"},
            {"id": 2, "focus": "Industry State of the Art & Implementations", "tool_name": "tavily_search", "search_query": f"{query} framework implementation production"},
            {"id": 3, "focus": "Challenges, Safety & Future Trends", "tool_name": "tavily_search", "search_query": f"{query} challenges safety trends"},
        ]

    for t in tasks:
        print(f"   • Task {t.get('id')}: [{t.get('focus')}] → Tool: `{t.get('tool_name')}` | Query: \"{t.get('search_query')}\"")

    notify_node_event("supervisor", "completed", {"tasks_count": len(tasks)})
    return {
        "research_tasks": tasks,
        "research_findings": [],
        "sources": [],
        "iteration_count": 0,
        "is_sufficient": False,
        "evaluation_critique": "",
    }


# ── 2. Fan-out: dispatch parallel workers ─────────────────────
def dispatch_workers(state: MainState) -> List[Send]:
    print(f"\n🚀 [Dispatcher] Spawning {len(state['research_tasks'])} parallel research workers…")
    return [
        Send("research_worker", {"query": state["query"], "task": task})
        for task in state["research_tasks"]
    ]


# ── 3. Research Worker (Invokes MCP Server Tools) ──────────────
# Workers are dispatched in PARALLEL via the Send API (all threads launch at t=0).
# However, MCP web searches complete quickly and independently.
# To avoid slamming the LLM API with 3 simultaneous synthesis requests,
# each worker staggers its LLM call by STAGGER_SECONDS * (task_id - 1).
WORKER_LLM_STAGGER_SECONDS = 4  # e.g. Worker1 → t=0s, Worker2 → t=4s, Worker3 → t=8s

def research_worker(state: ResearchWorkerState) -> dict:
    task = state["task"]
    task_id = task.get("id", 1)
    focus = task.get("focus", "Specialist Area")
    tool_name = task.get("tool_name", "tavily_search")
    query = task.get("search_query", state["query"])

    notify_node_event("research_worker", "started", {"task_id": task_id, "focus": focus, "tool": tool_name, "query": query})
    print(f"\n  🔬 [Worker {task_id}] Investigating: '{focus}'")
    print(f"     🌐 MCP Server Request: `{tool_name}`(query=\"{query}\")")

    # ── Step A: MCP web search runs immediately (no stagger — Tavily is fast) ──
    args = {"topic" if tool_name == "search_academic_papers" else "query": query, "max_results": 3}
    search_context = call_mcp_tool_sync(name=tool_name, arguments=args)

    found_urls = re.findall(r'https?://[^\s\)]+', search_context)
    sources = [{"url": u, "task_id": task_id, "focus": focus} for u in set(found_urls)]

    # ── Step B: Stagger LLM synthesis call to prevent concurrent API storms ──
    stagger_delay = WORKER_LLM_STAGGER_SECONDS * (int(str(task_id).replace("refine_", "") or 0) - 1)
    if stagger_delay > 0:
        notify_node_event("research_worker", "staggering", {"task_id": task_id, "focus": focus, "stagger_delay": stagger_delay})
        print(f"     ⏱️  [Worker {task_id}] Stagger delay {stagger_delay}s before LLM synthesis…")
        time.sleep(stagger_delay)

    notify_node_event("research_worker", "synthesizing", {"task_id": task_id, "focus": focus})
    system = SystemMessage(content=(
        "You are an elite research analyst. Analyze the evidence provided by the MCP server "
        "and synthesize comprehensive findings. Ensure all claims are grounded in the provided sources. "
        "Include bracketed citations like [1], [2] to reference findings. Be factual, dense, and rigorous."
    ))
    prompt = HumanMessage(content=(
        f"Research Dimension: {focus}\n"
        f"User Query: {state['query']}\n\n"
        f"--- Evidence Retrieved from MCP Server ({tool_name}) ---\n"
        f"{search_context}\n"
        f"---------------------------------------------------------\n\n"
        "Synthesize the findings into:\n"
        "• 3 In-depth bullet points with citations\n"
        "• 1 Key Takeaway on strategic significance"
    ))
    try:
        response = invoke_llm_with_retry(llm, [system, prompt], max_retries=3, initial_delay=2.0)
        content_text = response.content
    except Exception as e:
        print(f"     ⚠️ Worker {task_id} LLM retry exhausted: {e}. Falling back to structured search excerpts.")
        content_text = f"Key Findings for {focus}:\n" + "\n".join([f"• {s.get('url')}" for s in sources[:3]])

    finding_block = (
        f"### Dimension {task_id}: {focus}\n"
        f"**MCP Tool**: `{tool_name}` | **Query**: `{query}`\n\n"
        f"{content_text}\n"
    )

    print(f"  ✅ [Worker {task_id}] Completed research with {len(sources)} verified sources.")
    notify_node_event("research_worker", "completed", {"task_id": task_id, "focus": focus, "sources_count": len(sources)})
    return {
        "research_findings": [finding_block],
        "sources": sources,
    }


# ── 4. Evaluator (Reflexion & Sufficiency Gate) ────────────────
def evaluator_node(state: MainState) -> dict:
    current_cycle = state.get("iteration_count", 0)
    notify_node_event("evaluator", "started", {"cycle": current_cycle + 1, "sources_count": len(state.get("sources", []))})
    print(f"\n🔍 [Evaluator] Auditing research completeness (Cycle {current_cycle + 1}/{MAX_REFLEXION_CYCLES + 1})…")

    findings_summary = "\n\n".join(state["research_findings"])
    source_count = len(state.get("sources", []))

    system = SystemMessage(content=(
        "You are a rigorous research evaluator and scientific auditor. Review the accumulated research findings "
        "and determine whether they comprehensively, accurately, and factually answer the original query.\n"
        "Identify if any critical dimension has low evidence, failed searches, or missing factual depth.\n"
        "If critical gaps exist, set is_sufficient=False and provide a focused follow_up_query for an MCP tool."
    ))
    prompt = HumanMessage(content=(
        f"Original Query: {state['query']}\n"
        f"Total Sources Discovered: {source_count}\n\n"
        f"Accumulated Research Findings:\n{findings_summary}\n\n"
        "Evaluate the completeness and evidence quality of this research."
    ))

    # If we've reached the max reflection limit, accept findings and proceed
    if current_cycle >= MAX_REFLEXION_CYCLES:
        print(f"   ℹ️ Reached maximum reflection cycles ({MAX_REFLEXION_CYCLES}). Approving research for review.")
        notify_node_event("evaluator", "completed", {"is_sufficient": True, "score": 9, "max_cycles_reached": True})
        return {
            "is_sufficient": True,
            "iteration_count": current_cycle + 1,
            "follow_up_task": None,
        }

    try:
        structured_evaluator = llm.with_structured_output(ResearchEvaluation)
        eval_result: ResearchEvaluation = structured_evaluator.invoke([system, prompt])
        print(f"   📊 Evaluation Score: {eval_result.score}/10 | Sufficient: {eval_result.is_sufficient}")
        print(f"   💬 Evaluator Critique: {eval_result.critique[:120]}…")

        follow_up = None
        if not eval_result.is_sufficient and eval_result.follow_up_query:
            follow_up = {
                "id": f"refine_{current_cycle + 1}",
                "focus": eval_result.follow_up_focus or "Targeted Gap Fill",
                "tool_name": eval_result.follow_up_tool or "tavily_search",
                "search_query": eval_result.follow_up_query,
            }
            print(f"   🎯 Targeted Follow-Up Identified: [{follow_up['focus']}] → Query: \"{follow_up['search_query']}\"")

        notify_node_event("evaluator", "completed", {"is_sufficient": eval_result.is_sufficient, "score": eval_result.score, "has_gap": bool(follow_up)})
        return {
            "is_sufficient": eval_result.is_sufficient,
            "evaluation_critique": eval_result.critique,
            "iteration_count": current_cycle + 1,
            "follow_up_task": follow_up,
        }
    except Exception as e:
        print(f"   ⚠️ Evaluator parsing fallback: {e}")
        notify_node_event("evaluator", "completed", {"is_sufficient": True, "score": 8, "fallback": True})
        return {
            "is_sufficient": True,
            "iteration_count": current_cycle + 1,
            "follow_up_task": None,
        }


# ── 5. Evaluation Router: loops back if insufficient ───────────
def evaluation_router(state: MainState) -> str:
    if state.get("is_sufficient", True) or state.get("iteration_count", 0) > MAX_REFLEXION_CYCLES:
        return "human_approval"
    else:
        print("\n🔄 [Reflexion Loop] Routing to follow-up research worker to fill evidence gaps…")
        return "follow_up_worker"


# ── 6. Follow-up Worker (Fills gaps identified by Evaluator) ───
def follow_up_worker(state: MainState) -> dict:
    task = state.get("follow_up_task")
    if not task:
        return {}

    focus = task.get("focus", "Targeted Gap Fill")
    tool_name = task.get("tool_name", "tavily_search")
    query = task.get("search_query", state["query"])

    print(f"\n  🔬 [Follow-Up Worker] Deep-diving into missing area: '{focus}'")
    print(f"     🌐 MCP Server Request: `{tool_name}`(query=\"{query}\")")

    args = {"topic" if tool_name == "search_academic_papers" else "query": query, "max_results": 3}
    search_context = call_mcp_tool_sync(name=tool_name, arguments=args)

    found_urls = re.findall(r'https?://[^\s\)]+', search_context)
    sources = [{"url": u, "task_id": "follow_up", "focus": focus} for u in set(found_urls)]

    system = SystemMessage(content=(
        "You are an investigative researcher filling a specific gap identified during evaluation. "
        "Synthesize factual, cited insights strictly addressing the target query."
    ))
    prompt = HumanMessage(content=(
        f"Missing Dimension to Fill: {focus}\n"
        f"Original Query: {state['query']}\n\n"
        f"--- Live Evidence from MCP Server ({tool_name}) ---\n"
        f"{search_context}\n"
        f"-----------------------------------------------------\n\n"
        "Provide 3 dense, cited bullet points directly resolving this information gap."
    ))
    response = llm.invoke([system, prompt])

    finding_block = (
        f"### Follow-Up Dimension: {focus}\n"
        f"**MCP Tool**: `{tool_name}` | **Refinement Query**: `{query}`\n\n"
        f"{response.content}\n"
    )

    print(f"  ✅ [Follow-Up Worker] Successfully resolved gap with {len(sources)} additional verified sources.")
    return {
        "research_findings": [finding_block],
        "sources": sources,
    }


# ── 7. Human-in-the-Loop approval gate (with Steerable Guidance) ──
def human_approval_node(state: MainState) -> dict:
    source_count = len(state.get("sources", []))
    notify_node_event("human_approval", "waiting", {"sources_count": source_count})
    print("\n⏸️  [HITL] Pausing for human review / steering…")

    preview_sections = []
    for f in state["research_findings"]:
        lines = [line for line in f.splitlines() if line.startswith("### Dimension") or line.startswith("### Follow-Up") or line.startswith("### Human-Steered") or line.startswith("•")]
        preview_sections.append("\n".join(lines[:3]))

    summary_preview = "\n\n".join(preview_sections)

    decision = interrupt({
        "message": f"Research complete with {source_count} verified sources (Evaluated & Refined via MCP).",
        "findings_preview": summary_preview,
        "total_sources_gathered": source_count,
        "question": "Approve report? (Reply 'yes' to proceed, or type steering guidance to refine, e.g. 'Focus on cost tradeoffs'): ",
    })

    decision_str = str(decision).strip()
    is_approved = decision_str.lower() in ("yes", "y", "approve", "ok", "1", "true")
    is_rejected = decision_str.lower() in ("no", "n", "abort", "cancel")

    if is_approved:
        print("  ✅ Approved directly by human.")
        notify_node_event("human_approval", "completed", {"approved": True, "steered": False})
        return {"human_approved": True, "steering_feedback": None}
    elif is_rejected:
        print("  ❌ Rejected by human.")
        notify_node_event("human_approval", "completed", {"approved": False, "steered": False})
        return {"human_approved": False, "steering_feedback": None}
    else:
        print(f"  🧭 Steerable feedback received from human: \"{decision_str}\"")
        notify_node_event("human_approval", "completed", {"approved": True, "steered": True, "feedback": decision_str})
        return {"human_approved": True, "steering_feedback": decision_str}


# ── 8. Steering Worker (Gathers evidence addressing human guidance) ──
def steering_worker(state: MainState) -> dict:
    feedback = state.get("steering_feedback") or "Human guidance"
    notify_node_event("steering_worker", "started", {"feedback": feedback})
    print(f"\n🧭 [Steering Worker] Gathering research for human guidance: \"{feedback}\"")

    prompt = HumanMessage(content=(
        f"The user wants to steer the ongoing research on: '{state['query']}'.\n"
        f"User Steering Guidance: '{feedback}'\n\n"
        "Provide a concise search query (under 8 words) for a web search tool to retrieve relevant evidence."
    ))
    try:
        res = invoke_llm_with_retry(llm, [prompt], max_retries=2, initial_delay=1.0)
        query = res.content.strip().strip('"').strip("'")
    except Exception:
        query = f"{state['query']} {feedback}"

    print(f"     🌐 MCP Server Request: `tavily_search`(query=\"{query}\")")
    search_context = call_mcp_tool_sync("tavily_search", {"query": query, "max_results": 3})
    found_urls = re.findall(r'https?://[^\s\)]+', search_context)
    sources = [{"url": u, "task_id": "steering", "focus": f"Steering: {feedback[:30]}"} for u in set(found_urls)]

    system = SystemMessage(content=(
        "You are an investigative research analyst integrating human steering feedback into an existing study. "
        "Synthesize 3 dense bullet points grounded strictly in the provided MCP evidence."
    ))
    synth_prompt = HumanMessage(content=(
        f"Steering Instruction: {feedback}\n"
        f"Evidence from MCP tool:\n{search_context}\n\n"
        "Synthesize 3 bullet points with citations directly addressing the steering guidance."
    ))
    try:
        synth_res = invoke_llm_with_retry(llm, [system, synth_prompt], max_retries=2, initial_delay=1.0)
        synth_text = synth_res.content
    except Exception as e:
        synth_text = f"Key findings for {feedback}:\n" + "\n".join([f"• {u}" for u in set(found_urls)[:3]])

    block = (
        f"### Human-Steered Dimension: {feedback}\n"
        f"**MCP Tool**: `tavily_search` | **Steering Query**: `{query}`\n\n"
        f"{synth_text}\n"
    )
    print(f"  ✅ [Steering Worker] Completed research with {len(sources)} verified sources.")
    notify_node_event("steering_worker", "completed", {"sources_count": len(sources)})
    return {
        "research_findings": [block],
        "sources": sources,
        "steering_feedback": None,  # Reset feedback so pipeline advances to report
    }


# ── 9. Gate: route based on human decision / steering ─────────
def approval_router(state: MainState) -> str:
    if not state.get("human_approved", False):
        return END
    if state.get("steering_feedback"):
        return "steering_worker"
    return "report_pipeline"


